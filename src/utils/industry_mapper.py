def get_industry_name(induty_code: str) -> str:
    """업종 코드를 업종명으로 변환한다.

    Args:
        induty_code: DART의 induty_code (예: "264", "63120")

    Returns:
        업종명, 없으면 "기타"
    """
    if not induty_code:
        return "Unknown"

    code = str(induty_code).strip()

    # 정확한 매핑 먼저 확인
    if code in INDUSTRY_CODE_MAP:
        return INDUSTRY_CODE_MAP[code]

    # 부분 매핑 (예: "2612" → "26" 확인)
    for length in [4, 3, 2]:
        partial_code = code[:length]
        if partial_code in INDUSTRY_CODE_MAP:
            return INDUSTRY_CODE_MAP[partial_code]

    return "기타"
